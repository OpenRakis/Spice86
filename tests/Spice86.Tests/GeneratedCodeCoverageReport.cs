namespace Spice86.Tests;

using Microsoft.CodeAnalysis;

using System.Collections.Immutable;

using Xunit;

/// <summary>
/// Opt-in report: compiles the C# that a test's own emulator run generated (the
/// <see cref="GeneratedFileName"/> dump written under the creator's export folder) and appends one
/// tab-separated row per test to the file named by the <see cref="ReportPathVariable"/> environment
/// variable. When the variable is unset nothing is compiled and no file is written, so default test
/// runs are unchanged. The report never fails a test: it is the output.
/// </summary>
internal static class GeneratedCodeCoverageReport {
    /// <summary>Environment variable holding the path of the TSV report file. Unset or empty disables the report.</summary>
    public const string ReportPathVariable = "SPICE86_GENERATED_CODE_COVERAGE";

    /// <summary>Name of the generated C# dump compiled by the report. The copy under GeneratedProject is a duplicate and is ignored.</summary>
    public const string GeneratedFileName = "spice86dumpCfgGeneratedOverrides.cs";

    private const string NoPartitionsMarker = "// No CFG partitions were observed.";
    private const string NoGeneratedCodeStatus = "no-generated-code";
    private const string EmptyStatus = "empty";
    private const string OkStatus = "ok";
    private const string CompileErrorStatus = "compile-error";

    private static readonly object ReportFileLock = new();
    private static bool _reportFileInitialized;

    /// <summary>
    /// Compiles the C# generated by one run and appends its row to the report file, when the report
    /// environment variable is set. The first write of the process deletes the file and writes the header.
    /// </summary>
    /// <param name="exportFolder">Folder where the run dumped its recorded data, including the generated C#.</param>
    /// <param name="exePath">Path of the emulated program.</param>
    public static void RecordIfEnabled(string exportFolder, string exePath) {
        string? reportPath = Environment.GetEnvironmentVariable(ReportPathVariable);
        if (string.IsNullOrEmpty(reportPath)) {
            return;
        }
        string testName = TestContext.Current.Test?.TestDisplayName ?? "unknown";
        string row = BuildRow(testName, exePath, exportFolder);
        lock (ReportFileLock) {
            if (!_reportFileInitialized) {
                File.Delete(reportPath);
                File.AppendAllText(reportPath, Header() + Environment.NewLine);
                _reportFileInitialized = true;
            }
            File.AppendAllText(reportPath, row + Environment.NewLine);
        }
    }

    /// <summary>
    /// Builds one report row: test name, program file name, status, compile error ids, method count
    /// and line count of the generated C#. Status is <c>no-generated-code</c> when no dump was written,
    /// <c>empty</c> when the dump holds no partition, <c>ok</c> when it compiles and
    /// <c>compile-error</c> when it does not. The error, method and line columns are empty unless a
    /// dump was compiled.
    /// </summary>
    /// <param name="testName">Name of the test that ran the program.</param>
    /// <param name="exePath">Path of the emulated program.</param>
    /// <param name="exportFolder">Folder where the run dumped its recorded data.</param>
    /// <returns>The row, without a trailing newline.</returns>
    public static string BuildRow(string testName, string exePath, string exportFolder) {
        string program = Path.GetFileName(exePath);
        string? generatedFile = FindGeneratedFile(exportFolder);
        if (generatedFile == null) {
            return JoinColumns(testName, program, NoGeneratedCodeStatus, "", "", "");
        }
        string source = File.ReadAllText(generatedFile);
        if (source.StartsWith(NoPartitionsMarker, StringComparison.Ordinal)) {
            return JoinColumns(testName, program, EmptyStatus, "", "", "");
        }
        GeneratedCompilation compilation = new GeneratedOverrideCompiler().Compile(source);
        using MemoryStream peStream = compilation.PeStream;
        bool success = compilation.EmitResult.Success;
        string status = OkStatus;
        string errorIds = "";
        if (!success) {
            status = CompileErrorStatus;
            errorIds = JoinErrorIds(compilation.EmitResult.Diagnostics);
        }
        GeneratedCodeMetrics metrics = GeneratedCodeMetricsCollector.Collect(
            testName, compilation.SyntaxTree, compilation.EmitResult.Diagnostics);
        return JoinColumns(testName, program, status, errorIds, metrics.Methods.ToString(), metrics.Lines.ToString());
    }

    private static string? FindGeneratedFile(string exportFolder) {
        if (!Directory.Exists(exportFolder)) {
            return null;
        }
        return Directory.EnumerateFiles(exportFolder, GeneratedFileName, SearchOption.AllDirectories).FirstOrDefault();
    }

    private static string Header() {
        return JoinColumns("test", "program", "status", "errorIds", "methods", "lines");
    }

    private static string JoinErrorIds(ImmutableArray<Diagnostic> diagnostics) {
        return string.Join(",", diagnostics
            .Where(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error)
            .Select(diagnostic => diagnostic.Id)
            .Distinct(StringComparer.Ordinal)
            .OrderBy(id => id, StringComparer.Ordinal));
    }

    private static string JoinColumns(string test, string program, string status, string errorIds, string methods, string lines) {
        return string.Join('\t', [test, program, status, errorIds, methods, lines]);
    }
}
